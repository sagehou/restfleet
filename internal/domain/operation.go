package domain

import (
	"errors"
	"time"

	"github.com/google/uuid"
)

var (
	ErrOperationTransition = errors.New("invalid operation transition")
	ErrCredentialTestBusy  = errors.New("credential test already active")
	ErrJobLeaseLost        = errors.New("job lease is no longer owned")
	ErrIdempotencyReused   = errors.New("idempotency key reused")
)

// Operation is one immutable execution identity; retry never reopens a terminal operation.
type Operation struct {
	ID                                                  uuid.UUID
	Type, Status, Source                                string
	StorageCredentialID                                 uuid.UUID
	RepositoryID                                        *uuid.UUID
	SecretRevision                                      int64
	RequestedByUserID                                   uuid.UUID
	Attempt                                             int
	CreatedAt                                           time.Time
	DispatchedAt, AcknowledgedAt, StartedAt, FinishedAt *time.Time
	ErrorCode                                           string
}

func OperationTerminal(status string) bool {
	switch status {
	case "SUCCEEDED", "SUCCEEDED_WITH_WARNINGS", "FAILED", "CANCELED", "TIMED_OUT", "LOST", "REJECTED":
		return true
	}
	return false
}

// ValidOperationID reports whether an operation identity is a canonical
// UUIDv7, or the deterministic UUIDv5 key generated by a scheduled Agent run.
// Server-generated manual operations remain UUIDv7; the UUIDv5 exception is
// limited to the operation_id field and never grants authority.
func ValidOperationID(id uuid.UUID) bool {
	return (id.Version() == 7 || id.Version() == 5) && id.Variant() == uuid.RFC4122
}

func ValidateOperationTransition(from, to string) error {
	switch from {
	case "QUEUED":
		if to == "DISPATCHED" || to == "REJECTED" || to == "CANCELED" {
			return nil
		}
	case "DISPATCHED":
		if to == "ACKNOWLEDGED" || to == "LOST" || to == "FAILED" {
			return nil
		}
	case "ACKNOWLEDGED":
		if to == "RUNNING" {
			return nil
		}
	case "RUNNING":
		if to == "SUCCEEDED" || to == "SUCCEEDED_WITH_WARNINGS" || to == "FAILED" || to == "CANCEL_REQUESTED" || to == "TIMED_OUT" {
			return nil
		}
	case "CANCEL_REQUESTED":
		if to == "CANCELED" {
			return nil
		}
	}
	return ErrOperationTransition
}

// CredentialJob contains only lease and metadata, never materialized secrets.
type CredentialJob struct {
	ID, Owner           uuid.UUID
	Operation           Operation
	Credential          StorageCredential
	Repository          *Repository
	RepositoryAvailable bool
	LeaseExpiresAt      time.Time
	Payload             []byte
}

// CredentialTestOutcome codes are a closed vocabulary; subprocess/database
// errors are never persisted verbatim as operation or credential metadata.
func ValidCredentialTestCode(code string) bool {
	switch code {
	case "", "CONNECTION_FAILED", "TEST_TIMED_OUT", "CONFIG_UNSAFE", "REFRESH_FAILED",
		"CREDENTIAL_CHANGED", "CREDENTIAL_DISABLED", "SECRET_UNAVAILABLE", "WORKER_LOST":
		return true
	}
	return false
}

// BackupOperation is one scheduled backup run reported by an Agent. Credential
// test operations keep their own narrower table and type.
type BackupOperation struct {
	ID           uuid.UUID
	PlanID       uuid.UUID
	AgentID      uuid.UUID
	Type         string
	Source       string
	Status       string
	PlanRevision int64
	ConfigHash   string
	ScheduledAt  *time.Time
	StartedAt    *time.Time
	FinishedAt   *time.Time
	ExitCode     *int
	ErrorCode    string
	SnapshotID   string
	FilesDone    int64
	TotalFiles   int64
	BytesDone    int64
	TotalBytes   int64
	CreatedAt    time.Time
	UpdatedAt    time.Time

	ParentOperationID *uuid.UUID
	RootOperationID   *uuid.UUID
	CancelRequestedAt *time.Time
	CancelReason      string
	// DispatchedAt records that a JobDispatch was claimed for this operation.
	// The row stays QUEUED until JobAccepted so a lost dispatch is retried.
	DispatchedAt *time.Time
}

type BackupOperationProgress struct {
	OperationID  uuid.UUID
	PlanID       uuid.UUID
	AgentID      uuid.UUID
	PlanRevision int64
	ScheduledAt  time.Time
	Sequence     uint64
	Stage        string
	FilesDone    int64
	TotalFiles   int64
	BytesDone    int64
	TotalBytes   int64
	ObservedAt   time.Time
}

type BackupOperationResult struct {
	OperationID  uuid.UUID
	PlanID       uuid.UUID
	AgentID      uuid.UUID
	PlanRevision int64
	ScheduledAt  time.Time
	Status       string
	ErrorCode    string
	ExitCode     int
	SnapshotID   string
	FilesNew     int64
	DataAdded    int64
	FinishedAt   time.Time
}

// Snapshot indexes one successful backup run.
type Snapshot struct {
	PlanID       uuid.UUID
	SnapshotID   string
	AgentID      uuid.UUID
	HostID       uuid.UUID
	RepositoryID uuid.UUID
	OperationID  uuid.UUID
	CapturedAt   time.Time
	RecordedAt   time.Time
	FilesNew     int64
	BytesAdded   int64
}

// SnapshotEntry is one direct child of a snapshot path. Values come from a
// bounded `restic ls` scan; unknown Restic fields are not persisted.
type SnapshotEntry struct {
	Name    string    `json:"name"`
	Path    string    `json:"path"`
	Type    string    `json:"type"`
	Size    int64     `json:"size"`
	Mode    string    `json:"mode"`
	UID     int64     `json:"uid"`
	GID     int64     `json:"gid"`
	ModTime time.Time `json:"mtime"`
}

// SnapshotListResult is a cached directory page. It is not an authoritative
// tree index and may be discarded at any time.
type SnapshotListResult struct {
	OperationID  uuid.UUID
	RepositoryID uuid.UUID
	SnapshotID   string
	TreeID       string
	Path         string
	Truncated    bool
	Scanned      int
	Entries      []SnapshotEntry
	CollectedAt  time.Time
}
